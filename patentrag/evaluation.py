"""Evaluation: retrieval, RAG and agent metrics (SPEC Parts XVII, XIX–XXII).

Every metric here is implemented from its definition so the *measurement* is as transparent as
the thing measured. Retrieval metrics operate on ranked id-lists vs a relevance set; RAG metrics
decompose answer quality into context- and generation-level signals; agent metrics score tool
use and trajectories deterministically.
"""
from __future__ import annotations

import math
import re
from dataclasses import dataclass, field


# ===========================================================================
# Retrieval metrics (manual)
# ===========================================================================

def precision_at_k(ranked: list[str], relevant: set[str], k: int) -> float:
    r"""P@k = |relevant ∩ top-k| / k."""
    topk = ranked[:k]
    if not topk:
        return 0.0
    return sum(1 for d in topk if d in relevant) / k


def recall_at_k(ranked: list[str], relevant: set[str], k: int) -> float:
    r"""R@k = |relevant ∩ top-k| / |relevant|. Prior-art search cares deeply about recall."""
    if not relevant:
        return 1.0
    topk = set(ranked[:k])
    return len(topk & relevant) / len(relevant)


def reciprocal_rank(ranked: list[str], relevant: set[str]) -> float:
    r"""RR = 1/rank of the first relevant item (0 if none)."""
    for i, d in enumerate(ranked, start=1):
        if d in relevant:
            return 1.0 / i
    return 0.0


def mean_reciprocal_rank(rankings: list[list[str]], relevants: list[set[str]]) -> float:
    return sum(reciprocal_rank(r, rel) for r, rel in zip(rankings, relevants)) / max(1, len(rankings))


def dcg_at_k(gains: list[float], k: int) -> float:
    r"""DCG@k = Σ_{i=1}^{k} gain_i / log2(i+1)."""
    return sum(g / math.log2(i + 2) for i, g in enumerate(gains[:k]))


def ndcg_at_k(ranked: list[str], relevance: dict[str, float], k: int) -> float:
    r"""NDCG@k = DCG@k / IDCG@k using graded relevance (0 if no relevant items)."""
    gains = [relevance.get(d, 0.0) for d in ranked[:k]]
    ideal = sorted(relevance.values(), reverse=True)
    idcg = dcg_at_k(ideal, k)
    return dcg_at_k(gains, k) / idcg if idcg > 0 else 0.0


def f1(precision: float, recall: float) -> float:
    return 0.0 if (precision + recall) == 0 else 2 * precision * recall / (precision + recall)


