# ===========================================================================
# Helpers to evaluate a chunk-level retriever at document granularity
# ===========================================================================

def ranked_docs_from_chunks(ranked_chunk_ids: list[str], chunks_by_id: dict) -> list[str]:
    """Collapse a chunk ranking to a de-duplicated document ranking (first occurrence wins)."""
    seen: list[str] = []
    for cid in ranked_chunk_ids:
        did = chunks_by_id[cid].document_id
        if did not in seen:
            seen.append(did)
    return seen


def evaluate_retriever(search_fn, dataset: list[EvalExample], chunks_by_id: dict, ks=(5, 10)
                       ) -> dict[str, float]:
    """Aggregate R@k, P@k, MRR, NDCG@10 for a retriever `search_fn(query, k)->[(chunk_id,score)]`."""
    per_rr, per_ndcg = [], []
    agg = {f"recall@{k}": [] for k in ks}
    agg.update({f"precision@{k}": [] for k in ks})
    for ex in dataset:
        results = search_fn(ex.query, 50)
        doc_rank = ranked_docs_from_chunks([cid for cid, _ in results], chunks_by_id)
        for k in ks:
            agg[f"recall@{k}"].append(recall_at_k(doc_rank, ex.relevant_doc_ids, k))
            agg[f"precision@{k}"].append(precision_at_k(doc_rank, ex.relevant_doc_ids, k))
        per_rr.append(reciprocal_rank(doc_rank, ex.relevant_doc_ids))
        rel = {d: 1.0 for d in ex.relevant_doc_ids}
        per_ndcg.append(ndcg_at_k(doc_rank, rel, 10))
    result = {m: (sum(v) / len(v) if v else 0.0) for m, v in agg.items()}
    result["mrr"] = sum(per_rr) / max(1, len(per_rr))
    result["ndcg@10"] = sum(per_ndcg) / max(1, len(per_ndcg))
    return result


# ===========================================================================
# RAG metrics (manual, embedding-assisted)
# ===========================================================================

def split_sentences(text: str) -> list[str]:
    return [s.strip() for s in re.split(r"(?<=[.!?])\s+", text.strip()) if s.strip()]


def _cos(a, b) -> float:
    import numpy as np

    return float(a @ b / ((np.linalg.norm(a) * np.linalg.norm(b)) + 1e-12))


def answer_relevance(query: str, answer: str) -> float:
    """Cosine similarity between query and answer embeddings (is the answer on-topic?)."""
    from .dense import embed

    v = embed([query, answer])
    return max(0.0, _cos(v[0], v[1]))


def faithfulness(answer: str, contexts: list[str], threshold: float = 0.55) -> float:
    """Fraction of answer sentences supported by (max-similarity to) some context sentence.

    Groundedness proxy: a claim is 'supported' if it is semantically close to retrieved
    evidence. Not a substitute for an NLI model, but transparent and deterministic.
    """
    from .dense import embed

    sents = split_sentences(answer)
    if not sents:
        return 0.0
    ctx_sents = [s for c in contexts for s in split_sentences(c)] or contexts
    if not ctx_sents:
        return 0.0
    av = embed(sents)
    cv = embed(ctx_sents)
    sims = av @ cv.T
    supported = (sims.max(axis=1) >= threshold).sum()
    return float(supported) / len(sents)


def context_precision(retrieved_doc_ids: list[str], relevant: set[str]) -> float:
    if not retrieved_doc_ids:
        return 0.0
    return sum(1 for d in retrieved_doc_ids if d in relevant) / len(retrieved_doc_ids)


def context_recall(retrieved_doc_ids: list[str], relevant: set[str]) -> float:
    if not relevant:
        return 1.0
    return len(set(retrieved_doc_ids) & relevant) / len(relevant)


# ===========================================================================
# Agent metrics (deterministic)
# ===========================================================================

def tool_prf(predicted: list[str], gold: list[str]) -> dict[str, float]:
    """Tool-call precision/recall/F1 over multisets of tool names."""
    from collections import Counter

    p, g = Counter(predicted), Counter(gold)
    tp = sum((p & g).values())
    prec = tp / max(1, sum(p.values()))
    rec = tp / max(1, sum(g.values()))
    return {"precision": prec, "recall": rec, "f1": f1(prec, rec)}


def argument_correctness(predicted_args: list[dict], gold_args: list[dict]) -> float:
    """Fraction of aligned tool calls whose arguments match the gold arguments exactly."""
    if not gold_args:
        return 1.0
    n = min(len(predicted_args), len(gold_args))
    correct = sum(1 for i in range(n) if predicted_args[i] == gold_args[i])
    return correct / len(gold_args)


def trajectory_match(predicted: list[str], gold: list[str], mode: str = "exact") -> bool:
    if mode == "exact":
        return predicted == gold
    if mode == "unordered":
        from collections import Counter

        return Counter(predicted) == Counter(gold)
    if mode == "subset":
        return set(gold).issubset(set(predicted))
    raise ValueError(mode)
