def build_eval_dataset() -> list[EvalExample]:
    """The labeled benchmark, restricted to documents actually present in the bundled corpus."""
    from . import bootstrap as bs

    present = {d.doc_id for d in bs.ensure("docs_canonical")}
    out: list[EvalExample] = []
    for q, gold, ans, ev in _BENCH:
        gold_present = {g for g in gold if g in present}
        if gold_present:
            out.append(EvalExample(q, gold_present, ans, ev))
    return out


